// Helper search & filter functions
export function getCourseBySlug(slug: string): Course | undefined {
  return allCoursesData.find((c) => c.slug === slug || c.id === slug);
}

export function getCoursesByTrack(trackId: 'family' | 'youth' | 'institutions'): Course[] {
  return allCoursesData.filter((c) => c.trackId === trackId);
}
